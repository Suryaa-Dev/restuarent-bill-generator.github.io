export const tb = (key, lang, vars) => {
    let s = (STR[lang] || STR.en)[key] ?? STR.en[key] ?? key;
    if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.replace(`{${k}}`, v); });
    return s;
};
